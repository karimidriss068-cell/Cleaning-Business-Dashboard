// Regenerates src/lib/board/brains/hot.generated.ts from each brains/<slug>/_hot.md.
import fs from "node:fs"; import path from "node:path";
const dir = path.join(process.cwd(), "src/lib/board/brains");
const slugs = fs.readdirSync(dir).filter((s) => fs.existsSync(path.join(dir, s, "_hot.md"))).sort();
const body = slugs.map((s) => `  ${JSON.stringify(s)}: ${JSON.stringify(fs.readFileSync(path.join(dir, s, "_hot.md"), "utf8"))},`).join("\n");
fs.writeFileSync(path.join(dir, "hot.generated.ts"), `// GENERATED by scripts/gen-board-brains.mjs from brains/*/_hot.md. Do not edit by hand.\nexport const HOT_SHEETS: Record<string, string> = {\n${body}\n};\n`);
console.log("hot sheets:", slugs.length);
