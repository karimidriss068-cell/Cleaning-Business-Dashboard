import {
  Document,
  Page,
  View,
  Text,
  StyleSheet,
  renderToBuffer,
} from "@react-pdf/renderer";
import { money, num, shortDate } from "@/lib/format";
import type { ReportData } from "@/lib/report";

// MAKI brand palette (hex — @react-pdf has no CSS variables).
const C = {
  bg: "#1A0E0E",
  surface: "#2B1414",
  border: "#3D2020",
  crimson: "#8B1E2E",
  cream: "#F0E6D2",
  tan: "#B8A88C",
};

const s = StyleSheet.create({
  page: { backgroundColor: C.bg, color: C.cream, padding: 40, fontFamily: "Helvetica" },
  brand: { fontSize: 20, fontFamily: "Times-Roman", color: C.crimson, letterSpacing: 1 },
  brandOps: { fontFamily: "Times-Roman", color: C.tan },
  h1: { fontSize: 26, fontFamily: "Times-Roman", marginTop: 18, color: C.cream },
  sub: { fontSize: 10, color: C.tan, marginTop: 6 },
  rule: { borderBottomWidth: 1, borderBottomColor: C.border, marginVertical: 18 },
  grid: { flexDirection: "row", flexWrap: "wrap", gap: 10 },
  box: {
    width: "31.5%",
    backgroundColor: C.surface,
    borderWidth: 1,
    borderColor: C.border,
    borderRadius: 4,
    padding: 12,
  },
  label: { fontSize: 8, color: C.tan, textTransform: "uppercase", letterSpacing: 1 },
  value: { fontSize: 22, fontFamily: "Times-Roman", color: C.cream, marginTop: 6 },
  valueAccent: { color: C.crimson },
  sectionTitle: { fontSize: 9, color: C.tan, textTransform: "uppercase", letterSpacing: 1, marginBottom: 8 },
  funnelRow: { flexDirection: "row", alignItems: "flex-end", gap: 8, height: 90 },
  funnelCol: { flex: 1, alignItems: "center", justifyContent: "flex-end" },
  bar: { width: "100%", backgroundColor: C.crimson, borderRadius: 2 },
  funnelLabel: { fontSize: 8, color: C.tan, marginTop: 6 },
  funnelCount: { fontSize: 12, fontFamily: "Times-Roman", color: C.cream, marginBottom: 4 },
  footer: { position: "absolute", bottom: 30, left: 40, right: 40, fontSize: 8, color: C.tan },
});

function Box({ label, value, accent }: { label: string; value: string; accent?: boolean }) {
  return (
    <View style={s.box}>
      <Text style={s.label}>{label}</Text>
      <Text style={accent ? [s.value, s.valueAccent] : s.value}>{value}</Text>
    </View>
  );
}

export async function reportPdfBuffer(data: ReportData): Promise<Buffer> {
  const stages = [
    { label: "Leads", count: data.leads },
    { label: "Contacted", count: data.contacted },
    { label: "Qualified", count: data.qualified },
    { label: "Booked", count: data.booked },
    { label: "Showed", count: data.showed },
  ];
  const max = Math.max(...stages.map((x) => x.count), 1);

  const doc = (
    <Document title={`${data.account.name} — MAKI Ops report`}>
      <Page size="A4" style={s.page}>
        <View style={{ flexDirection: "row" }}>
          <Text style={s.brand}>MAKI </Text>
          <Text style={[s.brand, s.brandOps]}>Ops</Text>
        </View>
        <Text style={s.h1}>{data.account.name}</Text>
        <Text style={s.sub}>
          Performance report{data.account.niche ? ` · ${data.account.niche}` : ""} ·{" "}
          {shortDate(data.from)} – {shortDate(data.to)}
        </Text>

        <View style={s.rule} />

        <View style={s.grid}>
          <Box label="Total spend" value={money(data.spend)} />
          <Box label="Leads" value={num(data.leads)} />
          <Box label="Appointments booked" value={num(data.booked)} />
          <Box label="Appointments showed" value={num(data.showed)} />
          <Box label="Revenue" value={money(data.revenue)} />
          <Box
            label="Cost per appointment"
            value={data.cpa != null ? money(data.cpa) : "—"}
            accent
          />
        </View>

        <View style={s.rule} />

        <Text style={s.sectionTitle}>Funnel</Text>
        <View style={s.funnelRow}>
          {stages.map((st) => (
            <View key={st.label} style={s.funnelCol}>
              <Text style={s.funnelCount}>{num(st.count)}</Text>
              <View
                style={[s.bar, { height: Math.max((st.count / max) * 70, 3) }]}
              />
              <Text style={s.funnelLabel}>{st.label}</Text>
            </View>
          ))}
        </View>

        <Text style={s.footer}>
          Generated by MAKI Ops · Confidential — prepared for {data.account.name}.
        </Text>
      </Page>
    </Document>
  );

  return renderToBuffer(doc);
}
